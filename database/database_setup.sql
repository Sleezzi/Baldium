CREATE TABLE IF NOT EXISTS mods (	-- This table contains the list of mods installed on the server.
	id VARCHAR(8) PRIMARY KEY,		-- The modrinth ID of the mod
	version VARCHAR(32) NOT NULL	-- The mod version
);

CREATE TABLE IF NOT EXISTS mod_dependencies (									-- Contains mod dependencies.
	mod_id VARCHAR(8) NOT NULL REFERENCES mods(id) ON DELETE CASCADE,			-- The mod's Modrinth ID
	dependency_id VARCHAR(8) NOT NULL REFERENCES mods(id) ON DELETE RESTRICT	-- The Modrinth ID of the mod dependency
);

CREATE TABLE IF NOT EXISTS backup (
	frequency BIGINT DEFAULT 24,					-- Time between backups in hours
	keep BIGINT DEFAULT 10,							-- Number of backups to keep
	last_backup BIGINT DEFAULT 0					-- The date the last back was sent.
);


